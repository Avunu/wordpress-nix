"""wordpress-nix's standards-core product: the values ``wordpress-nix ci …`` and the
other core commands read (python-devops-nix standards/DESIGN.md §3).

What a site repository's CI needs from it:
- ``ci.relock_patch_paths = ("nix/vendor-hash",)``: the only path relock-push may
  push (``wordpress-nix ci apply-relock-patch``);
- ``ci.verify_relock``: composer.lock's URLs name their packages and versions, and
  nix/vendor-hash is a real hash (lockcheck.py; ``wordpress-nix ci verify-relock``);
- ``ci.decision_table``: §6.4 (verdict.py; ``wordpress-nix ci verdict``);
- the gates ``ci / flake``, ``ci / smoke`` and ``ci / audit``.

A site is a deployment project: no release flow (``main+deploy`` branching, no tags).
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path
from types import MappingProxyType
from typing import Any

from standards_core.product import (
    Branching,
    CiConfig,
    Engine,
    Hooks,
    Identity,
    Markers,
    Modules,
    Pins,
    Product,
)
from standards_core.scaffold.context import Checkout, default_load_checkout

from wordpress_nix_tools import __version__, lockcheck, verdict

DATA = Path(__file__).resolve().parent / "standards"
DOCS = "https://github.com/Avunu/wordpress/tree/main/docs"

GATES = ("flake", "smoke", "audit")

PRODUCT: Product


def load_checkout(root: Path) -> Checkout:
    return default_load_checkout(PRODUCT, root)


def discover(checkout: Checkout, cfg: Mapping[str, Any], modules: Mapping[str, bool]) -> dict[str, Any]:
    tracked = checkout.tracked
    return {
        "bedrock": "config/application.php" in tracked and "composer.json" in tracked,
        "vendor_hash": "nix/vendor-hash" in tracked,
    }


def gates(modules: Mapping[str, bool], cfg: Mapping[str, Any], facts: Mapping[str, Any]) -> list[str]:
    return list(GATES) if modules.get("ci", False) else []


def template_globals(checkout: Checkout, resolved: Any, ctx: Any) -> dict[str, Any]:
    return {"site": checkout.hyphen.removeprefix("site-")}


PRODUCT = Product(
    identity=Identity(
        name="wordpress-nix",
        cli="wordpress-nix",
        distribution="wordpress-nix-tools",
        version=__version__,
        table="wordpress-nix",
        env_prefix="WORDPRESS_NIX",
        report_key="wordpress_nix",
        sync_command="wordpress-init --sync",
        opt_in_hint=(
            "this repository has not opted in to wordpress-nix's standards: run "
            "`nix run github:Avunu/wordpress -- --sync --standards deployment`"
        ),
        docs_url=DOCS,
        config_required=False,
        description=f"wordpress-nix's conversion and site tools. See {DOCS}.",
    ),
    markers=Markers(
        managed="wordpress-nix:managed",
        header="wordpress-nix:managed — generated by wordpress-nix (`wordpress-init --sync`);",
        header_local="edit only inside the wordpress-nix:local region.",
        local="wordpress-nix:local",
        block_begin=">>> wordpress-nix: {name} (managed) >>>",
        block_end="<<< wordpress-nix: {name} (managed) <<<",
        html_begin="<!-- wordpress-nix:begin {name} -->",
        html_end="<!-- wordpress-nix:end {name} -->",
    ),
    engine=Engine(
        flake_input="wordpress-nix",
        repo="Avunu/wordpress",
        release_branch="main",
        url_key="dev-shell.wordpress-nix-url",
        install_spec=(
            "wordpress-nix-tools @ git+https://github.com/{owner}/{repo}@{rev}#subdirectory=py/wordpress_nix_tools"
        ),
        caller_stem="site-*",
        init_app="wordpress-init",
    ),
    pins=Pins(
        dir=".wordpress-nix/pins",
        lock_paths=("composer.lock",),
        managed_inputs=lambda ctx: ("wordpress-nix",),
    ),
    modules=Modules(
        names=(
            "dev-shell",
            "editorconfig",
            "hygiene",
            "commits",
            "releases",
            "dependabot",
            "ci",
            "repo-policy",
        ),
        needs=MappingProxyType({"repo-policy": ("ci",)}),
        github_only=("dependabot", "ci", "repo-policy", "releases"),
    ),
    data_root=DATA,
    hooks=Hooks(
        load_checkout=load_checkout,
        discover=discover,
        gates=gates,
        template_globals=template_globals,
    ),
    ci=CiConfig(
        gates=GATES,
        check_context="ci / {gate}",
        contexts=(
            ("ci / flake", "ci.yml"),
            ("ci / smoke", "ci.yml"),
            ("ci / audit", "ci.yml"),
        ),
        labels=MappingProxyType(
            {
                "dependencies": ("0366d6", "Pull requests that update a dependency", "dependabot"),
                "needs-review": (
                    "d93f0b",
                    "A dependency update the decision table leaves to a person",
                    "dependabot",
                ),
                "security": ("b60205", "A vulnerable version: cooldown bypassed", "dependabot"),
            }
        ),
        decision_table=verdict.DECISION_TABLE,
        relock_patch_paths=("nix/vendor-hash",),
        verify_relock=lockcheck.verify_relock,
    ),
    branching=MappingProxyType(
        {
            "main+deploy": Branching(
                name="main+deploy",
                flow="none",
                integration=lambda cfg: "main",
                release_branch=lambda cfg, facts: "",
            )
        }
    ),
    self_repo="Avunu/wordpress",
)
